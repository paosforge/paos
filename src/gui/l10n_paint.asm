; l10n_glyph(EDI scalar) -> RAX its 32 B bitmap in the embedded subset, or 0.
; Preserves every other register.
l10n_glyph:
    push rcx
    push rdx
    push rsi
    xor  ecx, ecx                       ; low
    mov  edx, L10N_GLYPH_COUNT          ; high (exclusive)
    lea  rsi, [rel l10n_glyph_cps]
.search:
    cmp  ecx, edx
    jae  .none
    lea  eax, [rcx + rdx]
    shr  eax, 1
    cmp  edi, [rsi + rax*4]
    je   .hit
    jb   .lower
    lea  ecx, [rax + 1]
    jmp  .search
.lower:
    mov  edx, eax
    jmp  .search
.hit:
    shl  eax, 5
    lea  rsi, [rel l10n_glyph_bits]
    add  rax, rsi
    jmp  .out
.none:
    xor  eax, eax
.out:
    pop  rsi
    pop  rdx
    pop  rcx
    ret

; l10n_scalar_at(RDI text, RSI bytes, RDX offset) -> EAX the scalar there,
;   -1 when it has no cell (malformed UTF-8, C0 including LF, DEL/C1, a
;   combining mark, past font8x16, a wide scalar missing from the subset), -2 at
;   the end; ECX its encoded bytes, EDX its cells (1 or 2), R10 its 16x16 bitmap
;   when wide (else 0). Preserves RBX, RDI, RSI, R8, R9, R11-R15.
l10n_scalar_at:
    push rbx
    push rdi
    push rsi
    push r8
    push r9
    push r11
    sub  rsp, 24                        ; {u32 scalar, u32 bytes} (+ alignment)
    mov  rcx, rsp
    call ue_utf8_decode                 ; EAX 1 decoded / 0 end / -1 invalid
    cmp  eax, 1
    je   .got
    test eax, eax
    mov  eax, -2
    jz   .ret
    mov  eax, -1
    jmp  .ret
.got:
    mov  ebx, [rsp]
    mov  edi, ebx
    call ue_cell_width                  ; 0/1/2 cells, -1 not a scalar
    mov  edx, eax
    xor  r10d, r10d
    cmp  edx, 1
    je   .narrow
    cmp  edx, 2
    jne  .none                          ; a combining mark or no scalar: no cell
    mov  edi, ebx
    call l10n_glyph
    test rax, rax
    jz   .none                          ; not in the embedded subset
    mov  r10, rax
    jmp  .ok
.narrow:
    cmp  ebx, 0x20
    jb   .none                          ; C0, LF included
    cmp  ebx, 0x7F
    jb   .ok
    cmp  ebx, 0xA0
    jb   .none                          ; DEL and C1
    cmp  ebx, FONT8X16_SCALARS
    jae  .none                          ; past font8x16
.ok:
    mov  eax, ebx
    mov  ecx, [rsp + 4]
    jmp  .ret
.none:
    mov  eax, -1
.ret:
    add  rsp, 24
    pop  r11
    pop  r9
    pop  r8
    pop  rsi
    pop  rdi
    pop  rbx
    ret

; l10n_measure(RSI text, EDX bytes) -> EAX its cells, or -1 when a scalar has no
; cell. Preserves every other register.
l10n_measure:
    push rcx
    push rdx
    push rdi
    push rsi
    push r10
    push r12
    push r13
    mov  rdi, rsi
    mov  esi, edx
    xor  r12d, r12d                     ; offset
    xor  r13d, r13d                     ; cells
.next:
    mov  edx, r12d
    call l10n_scalar_at
    cmp  eax, -2
    je   .end
    cmp  eax, -1
    je   .out
    add  r12d, ecx
    add  r13d, edx
    jmp  .next
.end:
    mov  eax, r13d
.out:
    pop  r13
    pop  r12
    pop  r10
    pop  rsi
    pop  rdi
    pop  rdx
    pop  rcx
    ret

; l10n_utf8_draw(RSI text, EDX bytes, R8D x, R9D y, EBX fg, ECX bg) -> R8D
;   advanced. Only after l10n_measure accepted the text: every scalar has a
;   cell. An ASCII run paints through fb_draw_str_n with its exact byte count
;   (catalog text has no NUL to stop at), so English is today's pixels and
;   cadence marks. Module-local: never a caller's raw-bytes painter (t6).
;   Preserves every other register.
l10n_utf8_draw:
    push rax
    push rcx
    push rdx
    push rdi
    push rsi
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15
    mov  r13, rsi                       ; text
    mov  r14d, edx                      ; bytes
    mov  r15d, ecx                      ; bg
    xor  r12d, r12d                     ; offset
.run:
    cmp  r12d, r14d
    jae  .done
    mov  r10d, r12d
.ascii:
    cmp  r10d, r14d
    jae  .ascii_end
    cmp  byte [r13 + r10], 0x80
    jae  .ascii_end
    inc  r10d
    jmp  .ascii
.ascii_end:
    cmp  r10d, r12d
    je   .scalar
    lea  rdi, [r13 + r12]
    mov  r11d, r10d
    sub  r11d, r12d                     ; exactly the run's bytes
    mov  ecx, r15d
    call fb_draw_str_n                  ; R8D advances 8 px a byte
    mov  r12d, r10d
    jmp  .run
.scalar:
    mov  rdi, r13
    mov  esi, r14d
    mov  edx, r12d
    call l10n_scalar_at
    test eax, eax
    js   .done                          ; measured first: never taken
    add  r12d, ecx
    mov  ecx, r15d
    cmp  edx, 2
    je   .wide
    mov  edx, eax
    call fb_draw_scalar
    add  r8d, 8
    jmp  .run
.wide:
    mov  rsi, r10
    call fb_draw_wide16
    add  r8d, 16
    jmp  .run
.done:
    pop  r15
    pop  r14
    pop  r13
    pop  r12
    pop  r11
    pop  r10
    pop  rsi
    pop  rdi
    pop  rdx
    pop  rcx
    pop  rax
    ret

; l10n_wrap(RSI text, EDX bytes, R8D x, R9D y, EBX fg, ECX bg, R10D cells a row,
;   R11D rows, EDI flags) -> EAX the rows the text takes, or -1 when (without
;   L10N_WRAP_HARD) it cannot fit whole: a word wider than a row, more than R11D
;   rows, or a scalar without a cell. L10N_WRAP_DRAW paints each line at the
;   next row; L10N_WRAP_HARD (the escaped English) breaks a word wider than a
;   row at the row's edge and stops after R11D rows. Spaces a break leaves at a
;   line start are dropped. Preserves every other register.
l10n_wrap:
    push rbx
    push rcx
    push rdx
    push rdi
    push rsi
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15
    push rbp
    mov  rbp, rsp
    sub  rsp, 72
    mov  [rbp - 8], rsi                 ; text
    mov  [rbp - 12], edx                ; bytes
    mov  [rbp - 16], r10d               ; cells a row
    mov  [rbp - 20], r11d               ; rows
    mov  [rbp - 24], edi                ; flags
    mov  [rbp - 28], r8d                ; x
    mov  [rbp - 32], r9d                ; the next row's y
    mov  [rbp - 36], ecx                ; bg
    mov  dword [rbp - 40], 0            ; rows used
    xor  r14d, r14d                     ; the line's start
.line:
    mov  rsi, [rbp - 8]
.skip:
    cmp  r14d, [rbp - 12]
    jae  .finish
    cmp  byte [rsi + r14], ' '
    jne  .start
    inc  r14d
    jmp  .skip
.start:
    mov  eax, [rbp - 40]
    cmp  eax, [rbp - 20]
    jae  .full                          ; more text, no row left
    mov  r12d, r14d                     ; position
    xor  r13d, r13d                     ; cells on this line
    mov  r15d, -1                       ; the last break: none yet
    mov  dword [rbp - 44], 0            ; where the line after that break starts
    mov  dword [rbp - 48], 0            ; the previous scalar
    mov  dword [rbp - 52], 0            ; its cells
.scan:
    mov  rdi, [rbp - 8]
    mov  esi, [rbp - 12]
    mov  edx, r12d
    call l10n_scalar_at                 ; EAX scalar, ECX bytes, EDX cells
    cmp  eax, -2
    je   .end_of_text
    cmp  eax, -1
    je   .refuse
    mov  r11d, eax                      ; the scalar
    mov  [rbp - 56], ecx
    cmp  r11d, ' '
    jne  .not_space
    mov  [rbp - 64], edx
    mov  rdi, [rbp - 8]
    mov  esi, [rbp - 12]
    mov  edx, r12d
    mov  ecx, [rbp - 16]
    call l10n_dnt_held
    mov  edx, [rbp - 64]
    test eax, eax
    jnz  .fit                           ; inside a do-not-translate span: no break here
    mov  r15d, r12d                     ; a break at a space; the space is dropped
    lea  eax, [r12 + 1]
    mov  [rbp - 44], eax
    jmp  .fit
.not_space:
    cmp  r12d, r14d
    je   .fit                           ; the line's first scalar
    cmp  dword [rbp - 48], ' '
    je   .fit
    cmp  edx, 2
    je   .wide_pair
    cmp  dword [rbp - 52], 2
    jne  .fit                           ; two narrow scalars: one word
.wide_pair:                             ; one of the pair is wide: a break, unless kinsoku forbids it
    mov  edi, r11d
    call l10n_no_break_before
    test eax, eax
    jnz  .fit
    mov  edi, [rbp - 48]
    call l10n_no_break_after
    test eax, eax
    jnz  .fit
    mov  r15d, r12d
    mov  [rbp - 44], r12d
.fit:
    lea  eax, [r13 + rdx]
    cmp  eax, [rbp - 16]
    jbe  .take
    cmp  r15d, -1
    jne  .break                         ; back to the last break (a space here is one)
    test dword [rbp - 24], L10N_WRAP_HARD
    jz   .refuse                        ; a word wider than a row
    cmp  r12d, r14d
    je   .refuse                        ; one scalar wider than a row
    mov  r15d, r12d                     ; HARD: break at the row's edge
    mov  [rbp - 44], r12d
.break:
    mov  ecx, r15d                      ; the line ends here
    mov  eax, [rbp - 44]                ; the next one starts here
    jmp  .emit
.take:
    mov  r13d, eax
    mov  [rbp - 48], r11d
    mov  [rbp - 52], edx
    add  r12d, [rbp - 56]
    jmp  .scan
.end_of_text:
    mov  ecx, r12d
    mov  eax, r12d
.emit:                                  ; [R14D, ECX) is one line; EAX the next line's start
    mov  [rbp - 60], eax
    test dword [rbp - 24], L10N_WRAP_DRAW
    jz   .counted
    mov  rsi, [rbp - 8]
    add  rsi, r14
    mov  edx, ecx
    sub  edx, r14d
    mov  r8d, [rbp - 28]
    mov  r9d, [rbp - 32]
    mov  ecx, [rbp - 36]
    call l10n_utf8_draw
.counted:
    add  dword [rbp - 32], L10N_ROW_PX
    inc  dword [rbp - 40]
    mov  r14d, [rbp - 60]
    jmp  .line
.full:
    test dword [rbp - 24], L10N_WRAP_HARD
    jz   .refuse
.finish:
    mov  eax, [rbp - 40]
    jmp  .out
.refuse:
    mov  eax, -1
.out:
    mov  rsp, rbp
    pop  rbp
    pop  r15
    pop  r14
    pop  r13
    pop  r12
    pop  r11
    pop  r10
    pop  r9
    pop  r8
    pop  rsi
    pop  rdi
    pop  rdx
    pop  rcx
    pop  rbx
    ret

; l10n_dnt_held(RDI text, ESI bytes, EDX the offset of a space, ECX cells a row)
;   -> EAX 1 when that space lies inside an occurrence of a do-not-translate
;   span no wider than a row: the line may not break there. An occurrence is
;   delimited: no ASCII letter or digit just before or just after it. The spans
;   are printable ASCII (the build refuses any other), one cell a byte.
;   Preserves every other register.
l10n_dnt_held:
    push r12                            ; align the word-byte helper calls
    push rbx
    push rcx
    push r8
    push r9
    push r10
    push r11
    lea  rbx, [rel l10n_dnt_spans]
.span:
    movzx r8d, byte [rbx]               ; the span's bytes
    test r8d, r8d
    jz   .no                            ; the list ends
    cmp  r8d, ecx
    ja   .next_span                     ; wider than a row: it may break at its spaces
    xor  r9d, r9d                       ; k: a space of the span
.inner:
    cmp  r9d, r8d
    jae  .next_span
    cmp  byte [rbx + 1 + r9], ' '
    jne  .inner_next
    mov  r10d, edx
    sub  r10d, r9d                      ; the occurrence would start here
    jb   .inner_next
    lea  eax, [r10 + r8]
    cmp  eax, esi
    ja   .inner_next                    ; it would run past the text
    xor  r11d, r11d
.same:
    cmp  r11d, r8d
    jae  .whole
    lea  eax, [r10 + r11]
    movzx eax, byte [rdi + rax]
    cmp  al, [rbx + 1 + r11]
    jne  .inner_next
    inc  r11d
    jmp  .same
.whole:
    test r10d, r10d
    jz   .left
    lea  eax, [r10 - 1]
    movzx eax, byte [rdi + rax]
    call l10n_word_byte
    test eax, eax
    jnz  .inner_next                    ; a letter or digit before it: not this term
.left:
    lea  eax, [r10 + r8]
    cmp  eax, esi
    jae  .held
    movzx eax, byte [rdi + rax]
    call l10n_word_byte
    test eax, eax
    jnz  .inner_next                    ; a letter or digit after it
.held:
    mov  eax, 1
    jmp  .out
.inner_next:
    inc  r9d
    jmp  .inner
.next_span:
    lea  rbx, [rbx + r8 + 1]
    jmp  .span
.no:
    xor  eax, eax
.out:
    pop  r11
    pop  r10
    pop  r9
    pop  r8
    pop  rcx
    pop  rbx
    pop  r12
    ret

; l10n_word_byte(EAX byte) -> EAX 1 for an ASCII letter or digit, else 0.
; Preserves every other register.
l10n_word_byte:
    push rcx
    mov  ecx, eax
    xor  eax, eax
    lea  ecx, [rcx - '0']
    cmp  ecx, 10
    jb   .word
    add  ecx, '0'
    or   ecx, 0x20
    sub  ecx, 'a'
    cmp  ecx, 26
    jae  .out
.word:
    mov  eax, 1
.out:
    pop  rcx
    ret

; l10n_help_paint(EDI page, ESI block k of the page or -1 for its title, R8D x,
;   R9D y, EBX fg, ECX bg, R10D cells a row, R11D rows) -> EAX 1 and EDX the rows
;   painted: the help record with its values, wrapped whole inside R10D x R11D
;   cells. EAX 0 and EDX 0, nothing painted, when it cannot be shown whole (no
;   valid help, out of range, a span outside the range, a template or value the
;   build would refuse, a scalar without a cell, too wide or too many rows).
;   Rows are L10N_ROW_PX apart. Preserves every other register.
l10n_help_paint:
    push r12                            ; align the formatter call
    mov  edx, L10N_WRAP_DRAW
    call l10n_paint_fmt
    pop  r12
    test eax, eax
    js   .none
    mov  edx, eax
    mov  eax, 1
    ret
.none:
    xor  eax, eax
    xor  edx, edx
    ret

; l10n_native_wrap(RSI native ASCII, R10D cells, R11D rows, EDX 0 measure
; or L10N_WRAP_DRAW paint) -> EAX rows, -1 if unavailable. Uses the SAME
; bounded escape and word/hard wrap as English fallback. Preserves every other
; register. Catalog metadata is <=255 printable bytes, never a UI action.
l10n_native_wrap:
    push rbx
    push rcx
    push rdx
    push rdi
    push rsi
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15
    sub  rsp, L10N_PAINT_ESC
    mov  r12d, edx
    test r10d, r10d
    jle  .bad
    test r11d, r11d
    jz   .bad
    mov  rdi, rsp
    call l10n_escape
    test eax, eax
    js   .out
    mov  rsi, rsp
    mov  edx, eax
    ; Prove a complete block fits BEFORE any cell is drawn. HARD fallback
    ; itself permits truncation; this public helper deliberately does not.
    push r11
    mov  r11d, -1
    mov  edi, L10N_WRAP_HARD
    call l10n_wrap
    pop  r11
    test eax, eax
    js   .out
    cmp  eax, r11d
    ja   .bad
    test r12d, L10N_WRAP_DRAW
    jz   .out
    test r11d, r11d
    jle  .bad
    mov  edi, L10N_WRAP_DRAW | L10N_WRAP_HARD
    call l10n_wrap
    jmp  .out
.bad:
    mov  eax, -1
.out:
    add  rsp, L10N_PAINT_ESC
    pop  r15
    pop  r14
    pop  r13
    pop  r12
    pop  r11
    pop  r10
    pop  r9
    pop  r8
    pop  rsi
    pop  rdi
    pop  rdx
    pop  rcx
    pop  rbx
    ret

; l10n_help_rows(EDI page, ESI block k or -1 for the title, R10D cells a row)
;   -> EAX the rows l10n_help_paint takes at that width, or -1 when it cannot be
;   shown whole at any height. The same composition and wrap with nothing drawn,
;   so H2's layout and the paint never disagree. Preserves every other register.
l10n_help_rows:
    push rdx
    push r11
    push r12                            ; align the formatter call
    mov  r11d, -1                       ; as many rows as it takes
    xor  edx, edx                       ; measure only
    call l10n_paint_fmt
    pop  r12
    pop  r11
    pop  rdx
    ret

; l10n_paint_fmt(EDI page, ESI block k or -1 for the title, R8D x, R9D y, EBX fg,
;   ECX bg, R10D cells a row, R11D rows, EDX 0 or L10N_WRAP_DRAW) -> EAX the rows
;   the composed record takes inside R10D x R11D cells (painted with DRAW), or
;   -1 when it cannot be shown whole. Module-local: H2 reaches it only through
;   the two entries above. Preserves every other register.
l10n_paint_fmt:
    push rbx
    push rcx
    push rdx
    push rdi
    push rsi
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15
    push rbp
    mov  rbp, rsp
    sub  rsp, L10N_FMT_FRAME
    mov  [rbp - 4], edi                 ; page
    mov  [rbp - 8], esi                 ; block, or -1
    mov  [rbp - 12], edx                ; flags
    mov  [rbp - 20], ecx                ; bg
    mov  [rbp - 24], r10d               ; cells a row
    mov  [rbp - 28], r11d               ; rows
    mov  [rbp - 32], r8d                ; x
    mov  [rbp - 36], r9d                ; y
    mov  [rbp - 40], ebx                ; fg
    mov  r12d, -1                       ; the result: refused until it fits
    cmp  esi, -1
    jne  .block
    call l10n_help_page                 ; EAX the title's id (0: none)
    jmp  .record
.block:
    call l10n_help_block                ; EAX its id (0: none)
.record:
    test eax, eax
    jz   .out                           ; no such record, or no valid help
    mov  edi, eax
    xor  esi, esi                       ; the help has no native English
    call l10n_text                      ; RSI text, EDX bytes, EAX 1 catalog / 0 native
    test eax, eax
    jz   .out
    call l10n_trusted
    test eax, eax
    jnz  .compose
    call l10n_paint_defect
    jmp  .out
.compose:                               ; R13 the trusted template, R14D its bytes
    mov  r13, rsi
    mov  r14d, edx
    mov  r15, rsp                       ; the composed record
    xor  r8d, r8d                       ; the template offset
    xor  r9d, r9d                       ; the composed bytes
.copy:
    cmp  r8d, r14d
    jae  .composed
    movzx eax, byte [r13 + r8]
    cmp  al, '{'
    je   .name
    cmp  al, '}'
    je   .out                           ; a lone '}' (the build refuses it)
    cmp  r9d, L10N_FMT_MAX
    jae  .out
    mov  [r15 + r9], al
    inc  r8d
    inc  r9d
    jmp  .copy
.name:                                  ; the name is [R10D, R11D), up to the next '}'
    lea  r10d, [r8 + 1]
    mov  r11d, r10d
.name_end:
    cmp  r11d, r14d
    jae  .out                           ; no '}': refused
    cmp  byte [r13 + r11], '}'
    je   .find
    inc  r11d                           ; (a '{' inside a name matches no value: refused below)
    jmp  .name_end
.find:
    xor  ebx, ebx                       ; j: the block's values in order (a title has none)
.param:
    mov  edi, [rbp - 4]
    mov  esi, [rbp - 8]
    mov  edx, ebx
    call l10n_help_param                ; EAX 1, RSI name, RDI value; 0 past the last
    test eax, eax
    jz   .out                           ; a name with no value: refused (the build refuses it first)
    mov  ecx, r10d
.same:
    movzx eax, byte [rsi]
    cmp  ecx, r11d
    je   .name_ends
    test eax, eax
    jz   .other
    cmp  al, [r13 + rcx]
    jne  .other
    inc  rsi
    inc  ecx
    jmp  .same
.name_ends:
    test eax, eax
    jz   .value                         ; this value's name, whole
.other:
    inc  ebx
    jmp  .param
.value:                                 ; RDI the value: data, escaped whole (t5)
    mov  rsi, rdi
    call strlen
    cmp  rax, L10N_VALUE_MAX
    ja   .out                           ; longer than the build allows: refused
    mov  edx, eax
    lea  rdi, [rsp + L10N_FMT_MAX]
    mov  ecx, L10N_VALUE_ESC
    call sec_text_escape                ; EAX its escaped bytes
    lea  ecx, [r9 + rax]
    cmp  ecx, L10N_FMT_MAX
    ja   .out
    xor  edx, edx
.append:
    cmp  edx, eax
    jae  .appended
    mov  cl, [rsp + L10N_FMT_MAX + rdx]
    mov  [r15 + r9], cl
    inc  edx
    inc  r9d
    jmp  .append
.appended:
    lea  r8d, [r11 + 1]                 ; past the '}'
    jmp  .copy
.composed:
    test r9d, r9d
    jz   .out                           ; nothing to show
    mov  rsi, r15
    mov  edx, r9d
    mov  r8d, [rbp - 32]
    mov  r9d, [rbp - 36]
    mov  ebx, [rbp - 40]
    mov  ecx, [rbp - 20]
    mov  r10d, [rbp - 24]
    mov  r11d, [rbp - 28]
    xor  edi, edi                       ; measure: it must fit whole
    call l10n_wrap
    test eax, eax
    js   .out
    mov  r12d, eax
    test dword [rbp - 12], L10N_WRAP_DRAW
    jz   .out
    mov  edi, L10N_WRAP_DRAW
    call l10n_wrap
.out:
    mov  eax, r12d
    mov  rsp, rbp
    pop  rbp
    pop  r15
    pop  r14
    pop  r13
    pop  r12
    pop  r11
    pop  r10
    pop  r9
    pop  r8
    pop  rsi
    pop  rdi
    pop  rdx
    pop  rcx
    pop  rbx
    ret

; l10n_no_break_before / l10n_no_break_after(EDI scalar) -> EAX 1 when no line
; may start / end with it (kinsoku). Preserve every other register.
l10n_no_break_before:
    push rcx
    push rsi
    lea  rsi, [rel l10n_kinsoku_nbb]
    mov  ecx, L10N_NBB_COUNT
    jmp  l10n_in_set
l10n_no_break_after:
    push rcx
    push rsi
    lea  rsi, [rel l10n_kinsoku_nba]
    mov  ecx, L10N_NBA_COUNT
l10n_in_set:                            ; (RCX, RSI pushed) EDI scalar, RSI dw set, ECX count
    push rdx
    xor  eax, eax
.next:
    test ecx, ecx
    jz   .out
    movzx edx, word [rsi]
    add  rsi, 2
    dec  ecx
    cmp  edx, edi
    jne  .next
    mov  eax, 1
.out:
    pop  rdx
    pop  rsi
    pop  rcx
    ret

str_l10n_paint_defect: db "[PAOS64] L10N_PAINT_DEFECT catalog text outside the image catalog; English [gui.l10n.paint]",13,10,0
