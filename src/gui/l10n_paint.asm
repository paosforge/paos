; l10n_trusted(RSI text, EDX bytes) -> EAX 1 when the whole span lies in the
; embedded catalog range (rc-sec t1/t2), else 0. Computed without overflow.
; Preserves every other register.
l10n_trusted:
    push rcx
    push rdx
    xor  eax, eax
    mov  edx, edx                       ; the length is a u32
    test edx, edx
    jz   .out                           ; len 0: never a whole record
    lea  rcx, [rel l10n_catalog_start]
    cmp  rsi, rcx
    jb   .out                           ; it starts before the range
    lea  rcx, [rel l10n_catalog_end]
    sub  rcx, rsi                       ; the room left = end - start
    jb   .out                           ; it starts past the end
    cmp  rdx, rcx
    ja   .out                           ; it runs past the end
    mov  eax, 1
.out:
    pop  rdx
    pop  rcx
    ret

