;; LAYER 6
;; EXPORTS res_pack_boot, res_pack_apply, res_pack_state, res_pack_stage, l10n_image_bind, l10n_text, l10n_state, l10n_reason, l10n_help_state, l10n_help_defects, l10n_help_page_count, l10n_help_page, l10n_help_block, l10n_help_param
;; IMPORTS core/localization, core/lib/mem, core/lib/str, core/lib/sha256, gui/lang_prefs, gui/resource_text, boot/serial
;; CAPS
;; OWNER rc-boot-claude
;; CONTEXT: bsp_only
; gui/res_pack_boot.asm — RCQ-38 S1 R1: the one boot point that may bind a
; translation pack (after lang_prefs_load, before lock_screen_init). It can
; never fail the boot: every outcome leaves either a bound, fully validated
; context or NO context, and the original native English strings render.
;
; English selected (the default, an unknown saved tag, no prefs arena): no
; descriptor, no source call, no I/O, no allocation, no bind.
;
; Otherwise the pack SOURCE fills a zeroed descriptor and returns a status.
; This image has no source: R2 adds the authenticated DATA-volume / Try-USB
; locator, which must build every expectation context from ONE verified
; release record (F5) and fit a measured boot budget (F6) before it returns
; RPB_SRC_OK. res_pack_apply never trusts pack bytes for an expectation.
;
; RCQ-38 l10n L1 (RPB_SRC_IMAGE): the reviewed catalog rides INSIDE the signed
; image (gui/l10n_catalog.inc, generated by l10n_bind_check.py emit; make lint
; refuses drift). Secure Boot covers its bytes, so no loader authenticates it.
; l10n_image_bind validates the embedded English PCAT1 every boot against
; expectations that are image constants, never catalog bytes; the pack line
; reports image=valid|INVALID, and an INVALID catalog gets an L10N_FALLBACK
; line (root 23:23:45 Q-A). l10n_text(id, english) returns the WHOLE catalog
; text or the WHOLE native English, never a mix; each English record == its
; in-source literal (l10n_bind_check).
;
; RCQ-38 catalogs (root 2026-10-16 19:12:27): the five other locales' UI and
; help PCAT1 ride in the same include and trusted range. The saved Settings
; selection (lang_prefs, read once here per boot) picks one; it is validated
; against the validated English view and image-constant expectations, and only
; a valid one is active (else locale_catalog_invalid: English, whole). A record
; it lacks is the English record. Literals outside the catalog stay English.
;
; RCQ-38 offline-help H1 (root GO 2026-10-11 02:41:49): the English help PCAT1
; rides in the same include, inside the same trusted range, and is validated
; every boot on its own (help=valid|INVALID on the pack line). The two verdicts
; are independent. Help ids (6000..6099) resolve through the help view only;
; an INVALID help makes every help id resolve to nothing for the whole boot.
; The page/block/parameter accessors read image tables, bounds-checked, and
; report nothing while the help is INVALID. No caller in H1: the UI is unchanged.
;
; Descriptor (RPD_SIZE bytes, source-filled, pointers to source-owned RAM):
;   +0  English PCAT1 bytes q   +8  English bytes d   +12 selected bytes d
;   +16 selected PCAT1 bytes q  +24 PRVA1 bytes q     +32 PRVA1 bytes d
;   +36 reserved d (zero)       +40 English catalog expectations q (locale 0)
;   +48 selected catalog expectations q (locale = selection, English view @80)
;   +56 map expectations q (English view @136)
;   +64 English view q (32 B)   +72 res_text runtime context q (88 B)

RPD_ENG         equ 0
RPD_ENG_LEN     equ 8
RPD_SEL_LEN     equ 12
RPD_SEL         equ 16
RPD_MAP         equ 24
RPD_MAP_LEN     equ 32
RPD_RSVD        equ 36
RPD_ENG_EXP     equ 40
RPD_SEL_EXP     equ 48
RPD_MAP_EXP     equ 56
RPD_ENG_VIEW    equ 64
RPD_CTX         equ 72
RPD_SIZE        equ 80

RPB_SRC_OK      equ 0                   ; descriptor filled
RPB_SRC_NONE    equ 1                   ; no pack reader in this image
RPB_SRC_NO_VOL  equ 2                   ; no PaOS DATA volume / Try-USB medium
RPB_SRC_NO_PACK equ 3                   ; medium present, no pack for the selection
RPB_SRC_LAST    equ 3                   ; any other status: a read failure

RPB_ST_UNTRIED  equ 0
RPB_ST_ENGLISH  equ 1                   ; English selected: nothing was tried
RPB_ST_NONE     equ 2
RPB_ST_NO_VOL   equ 3
RPB_ST_NO_PACK  equ 4
RPB_ST_READ     equ 5
RPB_ST_REFUSED  equ 6                   ; res_pack_stage names the refusing check
RPB_ST_LOADED   equ 7

RPB_STG_DESC    equ 1                   ; descriptor shape / locale / one English view
RPB_STG_ENG     equ 2
RPB_STG_SEL     equ 3
RPB_STG_MAP     equ 4
RPB_STG_BIND    equ 5

LGP_LOCALE_MAX  equ 5                   ; lang_prefs ordinals en..zh-Hans = 0..5

; res_pack_boot -> EAX 0. Once per boot; one serial state line per boot.
res_pack_boot:
    cmp  byte [rel res_pack_state], RPB_ST_UNTRIED
    jne  .out
    push rbx
    push r12
    sub  rsp, RPD_SIZE + 8
    mov  byte [rel res_pack_state], RPB_ST_ENGLISH
    call lang_prefs_get
    mov  r12d, eax
    mov  edi, eax
    call l10n_image_bind                ; RCQ-38 L1: the embedded carrier, every boot
    test r12d, r12d
    jz   .report                        ; English: no I/O, no allocation, no bind
    mov  rdi, rsp
    xor  esi, esi
    mov  edx, RPD_SIZE
    call memset
    mov  rdi, rsp
    mov  esi, r12d
    call res_pack_source
    mov  edx, eax
    mov  rdi, rsp
    mov  esi, r12d
    call res_pack_apply
.report:
    lea  rdi, [rel str_rpb_state]
    call serial_string
    movzx edi, byte [rel res_pack_state]
    call serial_hex64
    lea  rdi, [rel str_rpb_stage]
    call serial_string
    movzx edi, byte [rel res_pack_stage]
    call serial_hex64
    lea  rdi, [rel str_rpb_lang]
    call serial_string
    mov  edi, r12d
    call serial_hex64
    lea  rdi, [rel str_rpb_image]       ; RCQ-38 L1: the embedded catalog's state
    call serial_string
    lea  rdi, [rel str_l10n_ok]
    cmp  byte [rel l10n_reason], L10N_R_NONE
    je   .image_str                     ; the selection's catalog (and the English) validated
    lea  rdi, [rel str_l10n_invalid]
.image_str:
    call serial_string
    lea  rdi, [rel str_rpb_help]        ; RCQ-38 H1: the embedded help's state
    call serial_string
    lea  rdi, [rel str_l10n_invalid]
    cmp  byte [rel l10n_help_state], L10N_ST_OK
    jne  .help_str                      ; no valid English help: no help at all
    lea  rdi, [rel str_l10n_ok]
    cmp  byte [rel l10n_help_loc_state], L10N_ST_INVALID
    jne  .help_str
    lea  rdi, [rel str_l10n_english]    ; the selection's help failed: the English help, whole
.help_str:
    call serial_string
    lea  rdi, [rel str_rpb_marker]
    call serial_string
    add  rsp, RPD_SIZE + 8
    pop  r12
    pop  rbx
.out:
    xor  eax, eax
    ret

; S1: no reader. RDI zeroed descriptor, ESI selection 1..5 -> EAX status.
res_pack_source:
    mov  eax, RPB_SRC_NONE
    ret

; res_pack_apply(RDI descriptor, ESI selection 1..5, EDX source status)
; -> EAX res_pack_state. Unbinds FIRST, so no earlier context survives any
; outcome; binds only after the English catalog, the selected catalog and the
; map all validate against the source's trusted expectations.
res_pack_apply:
    push rbx
    push r12
    push r13
    mov  rbx, rdi
    mov  r12d, esi
    mov  r13d, edx
    xor  edi, edi
    call res_text_bind                  ; unbind first
    mov  byte [rel res_pack_stage], 0
    test r13d, r13d
    jz   .desc
    mov  eax, RPB_ST_READ
    cmp  r13d, RPB_SRC_LAST
    ja   .done                          ; unknown status: a read failure
    lea  eax, [r13 + 1]                 ; NONE/NO_VOL/NO_PACK -> states 2/3/4
    jmp  .done
.desc:
    mov  byte [rel res_pack_stage], RPB_STG_DESC
    lea  eax, [r12 - 1]
    cmp  eax, LGP_LOCALE_MAX - 1
    ja   .refuse_early
    cmp  dword [rbx + RPD_RSVD], 0
    jne  .refuse_early
    cmp  qword [rbx + RPD_ENG], 0
    je   .refuse_early
    cmp  qword [rbx + RPD_SEL], 0
    je   .refuse_early
    cmp  qword [rbx + RPD_MAP], 0
    je   .refuse_early
    cmp  qword [rbx + RPD_ENG_EXP], 0
    je   .refuse_early
    cmp  qword [rbx + RPD_SEL_EXP], 0
    je   .refuse_early
    cmp  qword [rbx + RPD_MAP_EXP], 0
    je   .refuse_early
    cmp  qword [rbx + RPD_ENG_VIEW], 0
    je   .refuse_early
    cmp  qword [rbx + RPD_CTX], 0
    je   .refuse_early
    mov  rax, [rbx + RPD_ENG_EXP]
    cmp  dword [rax], 0                 ; the English expectations are locale 0
    jne  .refuse_early
    mov  rax, [rbx + RPD_SEL_EXP]
    cmp  [rax], r12d                    ; the selected expectations name the selection
    jne  .refuse_early
    mov  rcx, [rbx + RPD_ENG_VIEW]
    cmp  [rax + 80], rcx                ; both reference the ONE English view
    jne  .refuse_early
    mov  rax, [rbx + RPD_MAP_EXP]
    cmp  [rax + 136], rcx
    jne  .refuse_early
    mov  byte [rel res_pack_stage], RPB_STG_ENG
    mov  rdi, [rbx + RPD_ENG]
    mov  esi, [rbx + RPD_ENG_LEN]
    mov  rdx, [rbx + RPD_ENG_EXP]
    mov  rcx, [rbx + RPD_ENG_VIEW]
    call l10n_catalog_validate
    cmp  eax, 1
    jne  .refuse
    mov  byte [rel res_pack_stage], RPB_STG_SEL
    mov  rdi, [rbx + RPD_SEL]
    mov  esi, [rbx + RPD_SEL_LEN]
    mov  rdx, [rbx + RPD_SEL_EXP]
    mov  rcx, [rbx + RPD_CTX]
    call res_catalog_load
    test eax, eax
    jnz  .refuse
    mov  byte [rel res_pack_stage], RPB_STG_MAP
    mov  rdi, [rbx + RPD_MAP]
    mov  esi, [rbx + RPD_MAP_LEN]
    mov  rdx, [rbx + RPD_MAP_EXP]
    mov  rcx, [rbx + RPD_CTX]
    call res_map_load
    test eax, eax
    jnz  .refuse
    mov  byte [rel res_pack_stage], RPB_STG_BIND
    mov  rdi, [rbx + RPD_CTX]
    call res_text_bind
    test eax, eax
    jnz  .refuse
    mov  byte [rel res_pack_stage], 0
    mov  eax, RPB_ST_LOADED
    jmp  .done
.refuse:
    ; A refused pack leaves no valid view behind for a later bind to reuse.
    mov  rax, [rbx + RPD_ENG_VIEW]
    mov  dword [rax + 24], 0
    mov  rax, [rbx + RPD_CTX]
    mov  dword [rax + 8 + 24], 0
    mov  dword [rax + 40 + 24], 0
.refuse_early:
    mov  eax, RPB_ST_REFUSED
.done:
    mov  [rel res_pack_state], al
    pop  r13
    pop  r12
    pop  rbx
    ret

L10N_ST_UNTRIED   equ 0                 ; the zero-fill (WDATA_BSS) initial state
L10N_ST_OK        equ 1                 ; the embedded English catalog validated
L10N_ST_INVALID   equ 2                 ; it did not: native English, reported
L10N_R_NONE       equ 0                 ; the zero-fill (WDATA_BSS) initial reason
L10N_R_INVALID    equ 2                 ; the embedded English catalog failed validation
L10N_R_LOC_INVALID equ 3                ; the selection's embedded catalog did: English, whole
L10N_CTX_SIZE     equ 96                ; l10n_catalog_validate's context (NATIVE_CORE.md)

; l10n_image_bind(EDI selection 0..5) -> EAX l10n_state. Once per boot, from
; res_pack_boot. The context comes from image constants only: locale 0, the
; generated revision, the schema + artifact SHA-256 pair, the static
; sha256_hash, authenticated = 1 (the bytes are part of the verified image).
; (RCQ-38 catalogs) A selection 1..5 then validates that locale's embedded UI
; catalog against the validated English view (l10n_locale_bind); only a valid
; one becomes active. Otherwise every UI record is the English one.
l10n_image_bind:
    push rbx
    push r12
    sub  rsp, 8
    mov  r12d, edi
    cmp  r12d, LGP_LOCALE_MAX
    jbe  .sel_ok
    xor  r12d, r12d                     ; never an index past the tag table
.sel_ok:
    movzx eax, byte [rel l10n_state]
    cmp  eax, L10N_ST_UNTRIED
    jne  .ret
    lea  rbx, [rel l10n_ctx]            ; zero image WDATA: locale 0, English view 0
    mov  dword [rbx + 4], L10N_CAT_REVISION
    lea  rdi, [rbx + 8]
    lea  rsi, [rel l10n_cat_en_expect]
    mov  edx, 64
    call memcpy
    lea  rax, [rel sha256_hash]
    mov  [rbx + 72], rax
    mov  dword [rbx + 88], 1
    lea  rdi, [rel l10n_cat_en]
    mov  esi, L10N_CAT_EN_BYTES
    mov  rdx, rbx
    lea  rcx, [rel l10n_en_view]
    call l10n_catalog_validate
    mov  byte [rel l10n_state], L10N_ST_INVALID
    mov  byte [rel l10n_reason], L10N_R_INVALID
    cmp  eax, 1
    jne  .report
    mov  byte [rel l10n_state], L10N_ST_OK
    mov  byte [rel l10n_reason], L10N_R_NONE
    test r12d, r12d
    jz   .report
    mov  edi, r12d
    xor  esi, esi                       ; the UI part
    lea  rdx, [rel l10n_en_view]
    lea  rcx, [rel l10n_loc_view]
    call l10n_locale_bind
    mov  byte [rel l10n_loc_state], L10N_ST_INVALID
    mov  byte [rel l10n_reason], L10N_R_LOC_INVALID
    cmp  eax, 1
    jne  .report                        ; the English stays active, reported
    mov  byte [rel l10n_loc_state], L10N_ST_OK
    mov  byte [rel l10n_reason], L10N_R_NONE
.report:
    mov  edi, r12d
    call l10n_help_bind                 ; H1: the embedded help, whatever the UI verdict
    cmp  byte [rel l10n_reason], L10N_R_NONE
    je   .ret
    lea  rdi, [rel str_l10n_fb]
    call serial_string
    lea  rdi, [rel l10n_tags]
    lea  rdi, [rdi + r12 * 8]
    call serial_string
    lea  rdi, [rel str_l10n_fb_reason]
    call serial_string
    lea  rdi, [rel str_l10n_r_loc_invalid]
    cmp  byte [rel l10n_reason], L10N_R_LOC_INVALID
    je   .reason_str
    lea  rdi, [rel str_l10n_r_invalid]
.reason_str:
    call serial_string
    lea  rdi, [rel str_l10n_fb_tail]
    call serial_string
.ret:
    movzx eax, byte [rel l10n_state]
    add  rsp, 8
    pop  r12
    pop  rbx
    ret

; (internal) l10n_help_bind(EDI selection 0..5, clamped): the embedded English
; help, once per boot from l10n_image_bind, after the UI verdict and independent
; of it. A fresh context from image constants only (locale 0, the generated help
; revision, its schema + artifact SHA-256 pair, the static sha256_hash,
; authenticated = 1). The state is INVALID before the verdict is read.
; (RCQ-38 catalogs) While the selection's UI catalog is active and the English
; help is valid, the selection's help validates against the English help view;
; INVALID leaves the English help in use. Preserves RBX and R12-R15.
l10n_help_bind:
    push rbx
    push r12
    sub  rsp, 8
    mov  r12d, edi
    lea  rbx, [rel l10n_ctx]
    mov  rdi, rbx
    xor  eax, eax
    mov  ecx, L10N_CTX_SIZE / 8
    rep  stosq                          ; nothing of the UI context is reused (no memset: no descriptor)
    mov  dword [rbx + 4], L10N_HELP_REVISION
    lea  rdi, [rbx + 8]
    lea  rsi, [rel l10n_help_en_expect]
    mov  edx, 64                        ; the help expectations: schema + artifact SHA-256
    call memcpy
    lea  rax, [rel sha256_hash]
    mov  [rbx + 72], rax
    mov  dword [rbx + 88], 1            ; authenticated: the help is part of the verified image
    lea  rdi, [rel l10n_cat_help_en]
    mov  esi, L10N_HELP_EN_BYTES
    mov  rdx, rbx
    lea  rcx, [rel l10n_help_view]
    call l10n_catalog_validate
    mov  byte [rel l10n_help_state], L10N_ST_INVALID
    cmp  eax, 1
    jne  .done                          ; the help is unavailable for the whole boot
    mov  byte [rel l10n_help_state], L10N_ST_OK
    cmp  byte [rel l10n_loc_state], L10N_ST_OK
    jne  .done                          ; English UI: the English help
    mov  edi, r12d
    mov  esi, 1                         ; the help part
    lea  rdx, [rel l10n_help_view]
    lea  rcx, [rel l10n_help_loc_view]
    call l10n_locale_bind
    mov  byte [rel l10n_help_loc_state], L10N_ST_INVALID
    cmp  eax, 1
    jne  .done
    mov  byte [rel l10n_help_loc_state], L10N_ST_OK
.done:
    add  rsp, 8
    pop  r12
    pop  rbx
    ret

; (internal) l10n_locale_bind(EDI selection 1..5, ESI part 0 UI / 1 help, RDX
; that part's validated English view, RCX out view) -> EAX 1 valid / 0. The
; bytes are the selection's l10n_loc_table span from l10n_catalog_start (numeric,
; inside the trusted range). A fresh context from image constants only: locale =
; the selection (lang_prefs ordinal == PCAT1 locale id), the part's generated
; revision, its schema + artifact SHA-256 from l10n_loc_expect, the static
; sha256_hash, the English view, authenticated = 1. Preserves RBX and R12-R15.
l10n_locale_bind:
    push rbx
    push r12
    push r13
    push r14
    push r15
    mov  r12d, edi
    mov  r13d, esi
    mov  r14, rdx
    mov  r15, rcx
    xor  eax, eax
    lea  ecx, [r12 - 1]
    cmp  ecx, L10N_LOCALES - 1
    ja   .out                           ; no locale row: nothing validates
    cmp  r13d, 1
    ja   .out
    lea  rbx, [rel l10n_ctx]
    mov  rdi, rbx
    mov  ecx, L10N_CTX_SIZE / 8
    rep  stosq                          ; nothing of an earlier context is reused
    mov  [rbx], r12d
    mov  dword [rbx + 4], L10N_CAT_REVISION
    test r13d, r13d
    jz   .revision
    mov  dword [rbx + 4], L10N_HELP_REVISION
.revision:
    lea  eax, [r12 - 1]
    lea  r12d, [r13 + rax * 2]          ; (row, part) index: 64 B expectations, 8 B span each
    mov  eax, r12d
    shl  eax, 6
    lea  rsi, [rel l10n_loc_expect]
    add  rsi, rax
    lea  rdi, [rbx + 8]
    mov  edx, 64                        ; schema + artifact SHA-256
    call memcpy
    lea  rax, [rel sha256_hash]
    mov  [rbx + 72], rax
    mov  [rbx + 80], r14                ; the validated English view of the same part
    mov  dword [rbx + 88], 1            ; authenticated: the catalog is part of the verified image
    lea  rax, [rel l10n_loc_table]
    lea  rax, [rax + r12 * 8]           ; dd offset, dd bytes
    mov  edi, [rax]
    mov  esi, [rax + 4]
    lea  rcx, [rel l10n_catalog_start]
    add  rdi, rcx
    mov  rdx, rbx
    mov  rcx, r15
    call l10n_catalog_validate
.out:
    pop  r15
    pop  r14
    pop  r13
    pop  r12
    pop  rbx
    ret

; l10n_text(EDI message id L10N_ID_* / L10N_HELP_ID_*, RSI native English
; cstr or 0) -> RSI text, EDX bytes, EAX 1 = the active catalog's record, 0 =
; the native English (RSI as passed; EDX 0 when it is 0). Always one whole
; message. Catalog text is NOT NUL-terminated: explicit-length seams only. The
; active catalog is the selection's validated embedded one, else the English
; (RCQ-38 catalogs); a record the selection lacks is the English record, whole.
; An id in the help band resolves through the help views only, and only while
; the English help is valid; asked for while it is not, it resolves to nothing
; and l10n_help_defects counts.
l10n_text:
    push rbx
    push r12
    sub  rsp, 8
    mov  ebx, edi
    mov  r12, rsi
    lea  eax, [rbx - L10N_HELP_ID_FIRST]
    cmp  eax, L10N_HELP_ID_LAST - L10N_HELP_ID_FIRST
    ja   .ui
    cmp  byte [rel l10n_help_state], L10N_ST_OK
    je   .help
    inc  dword [rel l10n_help_defects]  ; a help lookup with no valid help: counted (rc-sec Q-H3 3)
    jmp  .native
.help:
    lea  rdi, [rel l10n_help_view]
    cmp  byte [rel l10n_help_loc_state], L10N_ST_OK
    jne  .find
    lea  rdi, [rel l10n_help_loc_view]  ; the selection's help
    jmp  .find_loc
.ui:
    cmp  byte [rel l10n_state], L10N_ST_OK
    jne  .native
    lea  rdi, [rel l10n_en_view]
    cmp  byte [rel l10n_loc_state], L10N_ST_OK
    jne  .find
    lea  rdi, [rel l10n_loc_view]       ; the selection's UI catalog
.find_loc:
    mov  [rsp], rdi
    mov  esi, ebx
    call l10n_catalog_find
    test rax, rax
    jnz  .found
    lea  rdi, [rel l10n_en_view]        ; a record the selection lacks: the English one, whole
    lea  rcx, [rel l10n_help_view]
    lea  eax, [rbx - L10N_HELP_ID_FIRST]
    cmp  eax, L10N_HELP_ID_LAST - L10N_HELP_ID_FIRST
    cmovbe rdi, rcx
.find:
    mov  [rsp], rdi                     ; the view: its +0 is the validated buffer
    mov  esi, ebx
    call l10n_catalog_find
    test rax, rax
    jz   .native
.found:
    mov  edx, [rax + 8]                 ; PCAT1 entry: id, offset, bytes, flags
    mov  esi, [rax + 4]
    mov  rdi, [rsp]
    add  rsi, [rdi]
    mov  eax, 1
    jmp  .out
.native:
    xor  edx, edx
    test r12, r12
    jz   .native_len
    mov  rdi, r12
    call strlen
    mov  edx, eax
.native_len:
    mov  rsi, r12
    xor  eax, eax
.out:
    add  rsp, 8
    pop  r12
    pop  rbx
    ret

; l10n_help_page_count -> EAX L10N_HELP_PAGES while the help is valid, else 0.
l10n_help_page_count:
    xor  eax, eax
    cmp  byte [rel l10n_help_state], L10N_ST_OK
    jne  .none                          ; no valid help: no pages
    mov  eax, L10N_HELP_PAGES
.none:
    ret

; l10n_help_page(EDI page) -> EAX title message id, ECX block count; both 0
; for a page out of range or while the help is not valid. Preserves the rest.
l10n_help_page:
    xor  eax, eax
    xor  ecx, ecx
    cmp  byte [rel l10n_help_state], L10N_ST_OK
    jne  .none                          ; no valid help
    cmp  edi, L10N_HELP_PAGES
    jae  .none                          ; page out of range
    mov  ecx, edi
    lea  rax, [rel l10n_help_pages]
    lea  rax, [rax + rcx * 4]
    movzx ecx, byte [rax + 3]
    movzx eax, word [rax]
.none:
    ret

; l10n_help_block(EDI page, ESI block k of the page) -> EAX message id, ECX
; kind (L10N_HELP_KIND_*), EDX parameter count; all 0 when out of range or
; while the help is not valid. Preserves the rest.
l10n_help_block:
    call l10n_help_entry
    xor  ecx, ecx
    xor  edx, edx
    test rax, rax
    jz   .out                           ; no such block
    movzx ecx, byte [rax + 2]
    movzx edx, byte [rax + 4]
    movzx eax, word [rax]
.out:
    ret

; l10n_help_param(EDI page, ESI block k, EDX parameter j) -> EAX 1, RSI name,
; RDI value (NUL-terminated printable ASCII in the image's string table: data,
; painted escaped, never trusted text); EAX 0 and RSI = RDI = 0 when out of
; range or while the help is not valid. Preserves the rest.
l10n_help_param:
    push rcx
    call l10n_help_entry
    test rax, rax
    jz   .none
    movzx ecx, byte [rax + 4]
    cmp  edx, ecx
    jae  .none
    movzx ecx, byte [rax + 3]
    add  ecx, edx
    lea  rax, [rel l10n_help_params]
    lea  rax, [rax + rcx * 4]
    movzx esi, word [rax]
    movzx edi, word [rax + 2]
    lea  rax, [rel l10n_help_strtab]
    add  rsi, rax
    add  rdi, rax
    mov  eax, 1
    jmp  .out
.none:
    xor  eax, eax
    xor  esi, esi
    xor  edi, edi
.out:
    pop  rcx
    ret

; (internal) EDI page, ESI block k -> RAX that block's table entry, or 0 (the
; help not valid, page or k out of range). Preserves the rest.
l10n_help_entry:
    push rcx
    xor  eax, eax
    cmp  byte [rel l10n_help_state], L10N_ST_OK
    jne  .out                           ; no valid help
    cmp  edi, L10N_HELP_PAGES
    jae  .out                           ; page out of range
    mov  ecx, edi
    lea  rax, [rel l10n_help_pages]
    lea  rax, [rax + rcx * 4]
    movzx ecx, byte [rax + 3]
    cmp  esi, ecx
    jae  .none
    movzx ecx, byte [rax + 2]
    add  ecx, esi
    lea  rcx, [rcx + rcx * 4]           ; 5 B per block entry
    lea  rax, [rel l10n_help_blocks]
    add  rax, rcx
    jmp  .out
.none:
    xor  eax, eax
.out:
    pop  rcx
    ret

