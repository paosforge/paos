;; MODULE sec/update_public_policy
;; LAYER 2
;; EXPORTS update_public_policy_get, NUP_SIZE, NUP_EPOCH, NUP_MIN_SECURITY, NUP_MIN_VERSION, NUP_REVOKED_PAYLOAD_COUNT, NUP_REVOKED_BUILD_COUNT, NUP_RECORD_COUNT, NUP_POLICY_SHA, NUP_AUTHORITY_SHA, NUP_CHANNEL_POLICY_SHA, NUP_CONFIG_SHA, NUP_ASSET_SHA, NUP_MODULUS, NUP_EXPONENT, NUP_CHANNEL_LEN, NUP_FEED_LEN, NUP_ASSET_LEN, NUP_CHANNEL, NUP_FEED, NUP_ASSET, NUP_REVOKED_PAYLOAD, NUP_REVOKED_BUILD, NUP_RECORDS
;; IMPORTS core/lib/sha256
;; CAPS
;; OWNER saga:sec-native-update-policy
;; CONTEXT: bsp_only
; No-argument installed authority accessor. No caller-supplied policy, pointer,
; hash, verified flag or setter. Data is public, immutable authenticated image
; input generated by native_update_policy.py using existing Rescue validators.
; A checksum is corruption detection, NOT a new trust root or native signature.
; FS separately authenticates every untrusted PRL1/PCF1/state/current operand.

NUP_SIZE: equ 23408
NUP_EPOCH: equ 8
NUP_MIN_SECURITY: equ 16
NUP_MIN_VERSION: equ 24
NUP_REVOKED_PAYLOAD_COUNT: equ 36
NUP_REVOKED_BUILD_COUNT: equ 40
NUP_RECORD_COUNT: equ 44
NUP_POLICY_SHA: equ 48
NUP_AUTHORITY_SHA: equ 80
NUP_CHANNEL_POLICY_SHA: equ 112
NUP_CONFIG_SHA: equ 144
NUP_ASSET_SHA: equ 176
NUP_MODULUS: equ 256                 ; 32 little-endian limbs, existing RSA ABI
NUP_EXPONENT: equ 512
NUP_CHANNEL_LEN: equ 516
NUP_FEED_LEN: equ 520
NUP_ASSET_LEN: equ 524
NUP_CHANNEL: equ 528                 ; 32 including terminating/padding zeroes
NUP_FEED: equ 560                    ; 2201 including terminating/padding zeroes
NUP_ASSET: equ 2761                  ; 2201 including terminating/padding zeroes
NUP_REVOKED_PAYLOAD: equ 4976        ; 32x32
NUP_REVOKED_BUILD: equ 6000          ; 32x32
NUP_RECORDS: equ 7024                ; 32x512 original signed records

; update_public_policy_get() -> RAX=const view/RDX=NUP_SIZE, or BOTH zero.
; No state publication or cached verdict. Callee-saved registers preserved.
; Local stack: 352 + saved RBX, then existing bounded SHA call frames.
update_public_policy_get:
    push rbx
    sub rsp, 352
    lea rbx, [rel nup_blob]
    cmp dword [rbx], 1
    jne .refuse
    cmp dword [rbx+4], NUP_SIZE
    jne .refuse
    cmp qword [rbx+NUP_EPOCH], 0
    je .refuse
    cmp qword [rbx+NUP_MIN_SECURITY], 0
    je .refuse
    cmp dword [rbx+NUP_REVOKED_PAYLOAD_COUNT], 32
    ja .refuse
    cmp dword [rbx+NUP_REVOKED_BUILD_COUNT], 32
    ja .refuse
    mov eax, [rbx+NUP_RECORD_COUNT]
    dec eax
    cmp eax, 31
    ja .refuse
    cmp dword [rbx+NUP_EXPONENT], 65537
    jne .refuse
    test byte [rbx+NUP_MODULUS], 1
    jz .refuse
    test byte [rbx+NUP_MODULUS+255], 128
    jz .refuse
    mov eax, [rbx+NUP_CHANNEL_LEN]
    dec eax
    cmp eax, 30
    ja .refuse
    mov eax, [rbx+NUP_FEED_LEN]
    dec eax
    cmp eax, 2199
    ja .refuse
    mov eax, [rbx+NUP_ASSET_LEN]
    dec eax
    cmp eax, 2199
    ja .refuse
    ; Validate the complete fixed projection before using any variable length.
    mov rdi, rsp
    mov rsi, rbx
    mov edx, NUP_SIZE
    call sha256_hash
    test rax, rax
    jnz .refuse
    mov rdi, rsp
    lea rsi, [rel nup_binding_sha]
    mov ecx, 32
    repe cmpsb
    jne .refuse                     ; exact immutable projection binding
    lea rdi, [rbx+208]
    lea rsi, [rel nup_release_purpose]
    mov ecx, 48
    repe cmpsb
    jne .refuse
    lea rdi, [rbx+NUP_POLICY_SHA]
    lea rsi, [rbx+NUP_CHANNEL_POLICY_SHA]
    mov ecx, 32
    repe cmpsb
    jne .refuse                     ; same installed release policy
    ; Independent canonical SPKI hashing. Fixed DER RSA2048/e65537 prefix,
    ; big-endian modulus with mandatory leading00, fixed exponent suffix.
    lea rdi, [rsp+32]
    lea rsi, [rel nup_spki_prefix]
    mov ecx, 33
    rep movsb
    mov ecx, 256
.modulus:
    mov al, [rbx+NUP_MODULUS+rcx-1]
    stosb
    loop .modulus
    lea rsi, [rel nup_spki_suffix]
    mov ecx, 5
    rep movsb
    mov rdi, rsp
    lea rsi, [rsp+32]
    mov edx, 294
    call sha256_hash
    test rax, rax
    jnz .refuse
    mov rdi, rsp
    lea rsi, [rbx+NUP_AUTHORITY_SHA]
    mov ecx, 32
    repe cmpsb
    jne .refuse                     ; exact installed release-purpose SPKI
    mov rdi, rsp
    lea rsi, [rbx+NUP_ASSET]
    mov edx, [rbx+NUP_ASSET_LEN]
    call sha256_hash
    test rax, rax
    jnz .refuse
    mov rdi, rsp
    lea rsi, [rbx+NUP_ASSET_SHA]
    mov ecx, 32
    repe cmpsb
    jne .refuse
    mov rax, rbx
    mov edx, NUP_SIZE
    jmp .out
.refuse:
    xor eax, eax
    xor edx, edx
.out:
    add rsp, 352
    pop rbx
    ret

nup_release_purpose: db 'paos-release-payload-v1',0
nup_channel_purpose: db 'paos-update-channel-v1',0,0
nup_spki_prefix:
    db 0x30,0x82,0x01,0x22,0x30,0x0d,0x06,0x09,0x2a,0x86,0x48
    db 0x86,0xf7,0x0d,0x01,0x01,0x01,0x05,0x00,0x03,0x82,0x01
    db 0x0f,0x00,0x30,0x82,0x01,0x0a,0x02,0x82,0x01,0x01,0x00
nup_spki_suffix: db 0x02,0x03,0x01,0x00,0x01

%ifdef PAOS_NATIVE_UPDATE_POLICY_INCLUDE
%include PAOS_NATIVE_UPDATE_POLICY_INCLUDE
%else
; Same format0 refusal as unprovisioned Rescue. No fallback owner/LAB root.
nup_blob: times NUP_SIZE db 0
nup_blob_end:
nup_binding_sha: times 32 db 0
%endif
%if nup_blob_end - nup_blob != NUP_SIZE
    %error native_update_public_policy_size
%endif
