"""Rebuild the existing 9x19 AA atlas from pinned public font/FreeType sources."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[2]
INPUT = 'third_party/fonts/dejavu/'
MANIFEST_SHA = '615c5026befaa0de60591780d3e263df356f10e7941d415e18299b2db1f02232'
EXPECTED = '099427b2e8688fa303eb5a4366e50396b012fdf062b2a5009b688311816c0958'
FONT = 'src/gui/font_aa9x19.inc'
REQUIRED_INPUTS = {'LICENSE', 'tools/fonts/raster_aa.c', *(INPUT + n for n in
                   ('DejaVuSansMono.ttf', 'DejaVuSansMono.sfd', 'LICENSE', 'FreeType-FTL.txt',
                    'FreeType-LICENSE.txt', 'freetype-2.14.1.tar.xz', 'SOURCE.md'))}


def local(name):
    p = Path(name)
    if p.is_absolute() or '..' in p.parts or not p.parts:
        raise ValueError('unsafe source path')
    path = ROOT
    for part in p.parts:
        path = path / part
        if path.is_symlink():
            raise ValueError('source symlink: ' + name)
    if not path.is_file():
        raise ValueError('missing source/license/recipe: ' + name)
    return path


def admitted(name, expected):
    data = local(name).read_bytes()
    if len(data) > 16 * 1024 * 1024 or hashlib.sha256(data).hexdigest() != expected:
        raise ValueError('source/license/recipe hash: ' + name)
    return data


def inputs():
    m = json.loads(admitted(INPUT + 'SOURCES.json', MANIFEST_SHA))
    if m['schema'] != 'paos.dejavu-aa.source.v1' or m['font_version'] != '2.37-8-ubuntu' or m['freetype_version'] != '2.14.1':
        raise ValueError('source/rasterizer version')
    if set(m['files']) != REQUIRED_INPUTS:
        raise ValueError('source/license/recipe omission or extra input')
    return {n: admitted(n, row['sha256']) for n, row in m['files'].items()}


def command(argv, cwd, env):
    p = subprocess.run(argv, cwd=cwd, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=180)
    if p.returncode:
        raise ValueError('public rasterizer build failed: ' + str(argv[0]) + '\n' + p.stdout[-4000:].decode(errors='replace'))
    return p.stdout


def raster(data):
    if sys.platform != 'linux' or platform.machine() != 'x86_64':
        raise ValueError('recipe requires Linux x86-64 build host')
    # Rebuild from admitted public bytes on every invocation, with no host font,
    # Pillow, optional FreeType library or previously built rasterizer input.
    with tempfile.TemporaryDirectory(prefix='paos-aa-build-') as td:
        root = Path(td)
        archive = root / 'freetype.tar.xz'
        archive.write_bytes(data[INPUT + 'freetype-2.14.1.tar.xz'])
        with tarfile.open(archive) as t:
            for member in t.getmembers():
                p = Path(member.name)
                if p.is_absolute() or '..' in p.parts or member.issym() or member.islnk() or not (member.isfile() or member.isdir()):
                    raise ValueError('unsafe FreeType source member')
            t.extractall(root, filter='data')
        src = root / 'freetype-2.14.1'
        env = {'PATH': '/usr/bin:/bin', 'HOME': str(root), 'LC_ALL': 'C', 'CC': '/usr/bin/cc',
               'CFLAGS': '-O2 -fPIC', 'SOURCE_DATE_EPOCH': '0'}
        command(['./configure', '--without-zlib', '--without-bzip2', '--without-png',
                 '--without-harfbuzz', '--without-brotli', '--disable-shared', '--enable-static'], src, env)
        command(['/usr/bin/make', '-j4'], src, env)
        (root / 'raster_aa.c').write_bytes(data['tools/fonts/raster_aa.c'])
        command(['/usr/bin/cc', '-std=c99', '-O2', '-I' + str(src / 'include'),
                 str(root / 'raster_aa.c'), str(src / 'objs/.libs/libfreetype.a'),
                 '-lm', '-o', str(root / 'raster')], root, env)
        (root / 'DejaVuSansMono.ttf').write_bytes(data[INPUT + 'DejaVuSansMono.ttf'])
        result = command([str(root / 'raster'), str(root / 'DejaVuSansMono.ttf')], root, env)
        if len(result) != 95 * 9 * 19:
            raise ValueError('rasterizer coverage count')
        return result


def serialize(cells):
    if len(cells) != 16245:
        raise ValueError('ASCII coverage length')
    lines = [
        '; GENERATED by gauntlet_v2/tools/gen_font_aa9x19.py -- do not edit.',
        '; DejaVu Sans Mono DejaVuSansMono.ttf sha256 c805f9436dbc268644c1d9584f01a601a653e028e08fd74b9b949f6cf8304d88',
        '; Pillow 12.1.0, 15 px, cell 9x19, baseline 14, ASCII 32..126, 8-bit coverage.',
        '; DejaVu fonts: Copyright (c) 2003 Bitstream, Inc.; DejaVu changes are in public domain.',
        'FONT_AA_W     equ 9', 'FONT_AA_H     equ 19', 'FONT_AA_FIRST equ 32',
        'FONT_AA_LAST  equ 126', 'align 16', 'font_aa9x19:']
    for code in range(32, 127):
        lines.append(f'    ; {code:3d} {chr(code)!r}')
        cell = cells[(code - 32) * 171:(code - 31) * 171]
        for row in range(19):
            lines.append('    db ' + ','.join(f'0x{b:02X}' for b in cell[row * 9:(row + 1) * 9]))
    return ('\n'.join(lines) + '\n').encode('ascii')


def build():
    result = serialize(raster(inputs()))
    if hashlib.sha256(result).hexdigest() != EXPECTED:
        raise ValueError('regenerated atlas differs from original coverage/header')
    return result


def emit(out, result):
    # Refuse existing output and every linked ancestor before creating anything.
    absolute = out.absolute()
    for path in (absolute, *absolute.parents):
        if path.is_symlink():
            raise ValueError('output symlink')
    if absolute.exists():
        raise ValueError('output already exists')
    absolute.mkdir(parents=True)
    (absolute / 'font_aa9x19.inc').write_bytes(result)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--emit', type=Path)
    a = p.parse_args()
    try:
        result = build()
        if a.check:
            if local(FONT).read_bytes() != result:
                raise ValueError('shipped atlas drift')
            print('AA atlas: exact 95 DejaVu cells, 9x19, baseline14; public FreeType2.14.1')
        else:
            emit(a.emit, result)
    except (OSError, ValueError, KeyError, subprocess.SubprocessError, tarfile.TarError) as e:
        print('gen_aa: ' + str(e), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
