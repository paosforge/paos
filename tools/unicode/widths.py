"""Generate src/gui/vt/vt_tables.inc: DEC special graphics + Unicode width ranges.

Width follows the common wcwidth convention (glibc/xterm/libvterm family):
0 for combining marks (Mn, Me) and most format characters (Cf) except
U+00AD; 2 for East Asian Wide/Fullwidth; 1 otherwise. Deterministic from
Python's unicodedata (Unicode %s).
"""
import sys
# Explicit pinned UCD data, never the interpreter's Unicode database.
class UnicodeData:
    unidata_version = '15.0.0'

    def __init__(self, data):
        self.categories = ['Cn'] * 0x110000
        self.widths = ['N'] * 0x110000
        for name, target in [('DerivedGeneralCategory.txt', self.categories),
                             ('EastAsianWidth.txt', self.widths)]:
            for line in data[name].splitlines():
                body = line.split('#', 1)[0].strip()
                if not body:
                    continue
                field, value = body.split(';')
                ends = field.strip().split('..')
                lo, hi = int(ends[0], 16), int(ends[-1], 16)
                if not 0 <= lo <= hi < 0x110000:
                    raise ValueError('UCD range')
                target[lo:hi + 1] = [value.strip()] * (hi - lo + 1)

    def category(self, ch):
        return self.categories[ord(ch)]

    def east_asian_width(self, ch):
        return self.widths[ord(ch)]

unicodedata = None


def configure(data):
    global unicodedata
    unicodedata = UnicodeData(data)

DEC = {0x5f: 0x00a0, 0x60: 0x25c6, 0x61: 0x2592, 0x62: 0x2409, 0x63: 0x240c, 0x64: 0x240d,
       0x65: 0x240a, 0x66: 0x00b0, 0x67: 0x00b1, 0x68: 0x2424, 0x69: 0x240b, 0x6a: 0x2518,
       0x6b: 0x2510, 0x6c: 0x250c, 0x6d: 0x2514, 0x6e: 0x253c, 0x6f: 0x23ba, 0x70: 0x23bb,
       0x71: 0x2500, 0x72: 0x23bc, 0x73: 0x23bd, 0x74: 0x251c, 0x75: 0x2524, 0x76: 0x2534,
       0x77: 0x252c, 0x78: 0x2502, 0x79: 0x2264, 0x7a: 0x2265, 0x7b: 0x03c0, 0x7c: 0x2260,
       0x7d: 0x00a3, 0x7e: 0x00b7}


def width(cp):
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if cp == 0xad:
        return 1
    if cat in ("Mn", "Me") or (cat == "Cf" and cp != 0xad) or 0x1160 <= cp <= 0x11ff or cp == 0x200b:
        return 0
    if unicodedata.east_asian_width(ch) in ("W", "F"):
        return 2
    return 1


def ranges(value):
    out, start = [], None
    for cp in range(0x300, 0x110000):
        if 0xd800 <= cp <= 0xdfff:
            continue
        w = (unicodedata.category(chr(cp)) in ("Mn", "Me")) if value == "marks" else width(cp) == value
        if w and start is None:
            start = cp
        if not w and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, 0x10ffff))
    return out


def main():
    zero, wide = ranges(0), ranges(2)
    lines = ["; GENERATED by gauntlet_v2/tools/vt/gen_vt_tables.py (Unicode %s) - do not edit"
             % unicodedata.unidata_version,
             "vt_dec_graphics:            ; 0x5f..0x7e -> codepoint"]
    lines.append("    dd " + ",".join("0x%x" % DEC[c] for c in range(0x5f, 0x7f)))
    for name, rows in (("vt_width0", zero), ("vt_width2", wide), ("vt_marks", ranges("marks"))):
        lines.append("%s_count: dd %d" % (name, len(rows)))
        lines.append("%s:                    ; sorted inclusive [lo, hi] pairs" % name)
        for i in range(0, len(rows), 8):
            lines.append("    dd " + ",".join("0x%x,0x%x" % r for r in rows[i:i + 8]))
    sys.stdout.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
